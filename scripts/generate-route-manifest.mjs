/**
 * Writes src/lib/site-routes.generated.ts — every static, publicly reachable
 * route under src/app/(site).
 *
 * The sitemap used to be a hand-kept list, and it had drifted: pages that had
 * shipped were missing from it for months. This runs from `prebuild` (and
 * `predev`), so adding a page adds it to the sitemap and nobody has to
 * remember.
 *
 * It is generated rather than read from the filesystem at request time because
 * Next only traces the files a route actually imports into the deployment —
 * src/app would not be there to walk on Vercel.
 *
 * What is left out, and why:
 *   - dynamic segments ([slug], [[...tool]]) — there is no list of values here.
 *     Product and blog detail pages come from Sanity in sitemap.ts instead.
 *   - the (auth) and (protected) groups — they need a session, so all a crawler
 *     can ever reach is the sign-in page.
 *   - DENY below: pages that resolve fine but should not be indexed.
 */
import { readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const siteRoot = path.join(root, 'src/app/(site)')
const target = path.join(root, 'src/lib/site-routes.generated.ts')

/** Route groups whose pages are behind a session. */
const PRIVATE_GROUPS = new Set(['(auth)', '(protected)'])

/** Reachable, but not pages a search engine should hold: */
const DENY = new Set([
  '/verify', // one-shot link target, meaningless without its token
  '/search', // a view of other pages, with nothing of its own
])

const isGroup = (segment) => segment.startsWith('(') && segment.endsWith(')')
const isDynamic = (segment) => segment.startsWith('[')

async function walk(dir, route) {
  const entries = await readdir(dir, { withFileTypes: true })
  const routes = entries.some((e) => e.isFile() && /^page\.(tsx|ts|jsx|js)$/.test(e.name))
    ? [route === '' ? '/' : route]
    : []

  for (const entry of entries) {
    if (!entry.isDirectory()) continue
    if (isDynamic(entry.name)) continue
    if (isGroup(entry.name)) {
      if (PRIVATE_GROUPS.has(entry.name)) continue
      // A group adds nothing to the URL — descend without extending the path.
      routes.push(...(await walk(path.join(dir, entry.name), route)))
      continue
    }
    routes.push(...(await walk(path.join(dir, entry.name), `${route}/${entry.name}`)))
  }

  return routes
}

const routes = (await walk(siteRoot, ''))
  .filter((route) => !DENY.has(route))
  .sort()

const body = `// Generated by scripts/generate-route-manifest.mjs — do not edit.
// Regenerated on every \`npm run build\` and \`npm run dev\`.

/** Every static, publicly reachable page under src/app/(site). */
export const SITE_ROUTES = [
${routes.map((route) => `  '${route}',`).join('\n')}
] as const
`

await writeFile(target, body)
console.log(`${path.relative(root, target)} — ${routes.length} routes`)
