const MONTH_JP = '月'

/** 2025-11-24 → 2025年11月24日 */
export function formatBlogDate(iso: string) {
  const [year, month, day] = iso.split('-')
  return `${year}年${Number(month)}${MONTH_JP}${Number(day)}日`
}

/** Newest first — the API's own ordering is by an editor-set sort field that
 *  does not survive the trip here, and a date order is what readers expect. */
export const BLOG_POSTS_BY_DATE = [...BLOG_POSTS].sort((a, b) =>
  b.date.localeCompare(a.date)
)

export function getPost(slug: string) {
  return BLOG_POSTS.find((post) => post.slug === slug)
}

/** Prev/next within the sorted list, for the detail page's bottom bar. */
export function getNeighbours(slug: string) {
  const index = BLOG_POSTS_BY_DATE.findIndex((post) => post.slug === slug)
  return {
    prev: index > 0 ? BLOG_POSTS_BY_DATE[index - 1] : undefined,
    next:
      index >= 0 && index < BLOG_POSTS_BY_DATE.length - 1
        ? BLOG_POSTS_BY_DATE[index + 1]
        : undefined,
  }
}

/** Everything except the given slug, for the "関連記事" grid. */
export function getRelated(slug: string, limit = 3) {
  return BLOG_POSTS_BY_DATE.filter((post) => post.slug !== slug).slice(0, limit)
}
