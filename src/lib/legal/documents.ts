// The two legal documents, transcribed from the RTFs the client supplied
// (privacypolicy and terms.rtf in the repo root). The source is bilingual,
// Japanese above Chinese; this site is Japanese-only, so only the Japanese
// half is carried over.
//
// Passages the client still has to fill in are left in the 【…】 brackets the
// source uses, rather than guessed at. LegalDocumentView renders them as
// visible blanks, so what is outstanding is obvious on the page.

export type LegalBlock =
  | { type: 'p'; text: string }
  | { type: 'list'; items: { marker: string; text: string }[] }
  | { type: 'fields'; items: { label: string; value: string }[] }

export type LegalSection = {
  /** Absent on the opening passage, which runs before 第1条. */
  heading?: string
  blocks: LegalBlock[]
}

export type LegalDocument = {
  slug: string
  title: string
  description: string
  sections: LegalSection[]
  /** 制定日 and 運営会社, set below the document. */
  colophon: { label: string; value: string }[]
  copyright: string
}

